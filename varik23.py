# Запрашиваем число у пользователя
number = int(input("Введите целое число: "))

print("-" * 30)

# --- Задача 1: Проверить, является ли число двузначным и нечётным ---
# Двузначное число: от 10 до 99 включительно (или от -99 до -10)
# Нечетное: остаток от деления на 2 не равен 0

if (10 <= abs(number) <= 99) and (number % 2 != 0):
    print(f"1. Число {number} является двузначным и нечётным.")
else:
    print(f"1. Число {number} НЕ является двузначным и нечётным.")


# --- Задача 2: Определить, является ли число кратным 11 ---
# Кратно 11: делится на 11 без остатка

if number % 11 == 0:
    print(f"2. Число {number} кратно 11.")
else:
    print(f"2. Число {number} не кратно 11.")


# --- Задача 3: Определить, является ли число числом Армстронга ---
# Число Армстронга для трехзначных: abc = a^3 + b^3 + c^3
# Мы сделаем универсальную проверку (для любого количества цифр)

# Преобразуем число в строку, чтобы узнать количество цифр (длину)
num_str = str(abs(number)) 
num_len = len(num_str)

# Считаем сумму цифр в степени количества цифр
sum_of_powers = 0
for digit in num_str:
    sum_of_powers += int(digit) ** num_len

if sum_of_powers == abs(number):
    print(f"3. Число {number} является числом Армстронга.")
else:
    print(f"3. Число {number} НЕ является числом Армстронга.")