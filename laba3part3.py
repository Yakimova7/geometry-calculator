import math

# Границы отрезка и шаг
start = -5.0
end = 5.0
step = 0.5

# Определяем номер варианта (например, пусть будет 23, как в прошлом задании)
# Если номер четный - используем while, если нечетный - repeat until
variant_number = 23 

print(f"{'x':>6} | {'y':>10}")
print("-" * 20)

x = start

if variant_number % 2 == 0:
    # --- ЧЕТНЫЙ ВАРИАНТ: Конструкция while do (цикл с предусловием) ---
    print("Используется конструкция: while do")
    while x <= end:
        # ЗДЕСЬ ВСТАВЬТЕ ВАШУ ФУНКЦИЮ
        # Например, y = math.sin(x) + x**2
        y = math.sin(x) # <-- ЗАМЕНИТЕ ЭТО НА СВОЮ ФУНКЦИЮ
        
        print(f"{x:6.1f} | {y:10.4f}")
        x += step

else:
    # --- НЕЧЕТНЫЙ ВАРИАНТ: Конструкция repeat until (цикл с постусловием) ---
    print("Используется конструкция: repeat until")
    while True: # Это аналог repeat
        # ЗДЕСЬ ВСТАВЬТЕ ВАШУ ФУНКЦИЮ
        y = math.sin(x) # <-- ЗАМЕНИТЕ ЭТО НА СВОЮ ФУНКЦИЮ
        
        print(f"{x:6.1f} | {y:10.4f}")
        x += step
        
        # Это аналог until (условие выхода из цикла)
        if x > end:
            break