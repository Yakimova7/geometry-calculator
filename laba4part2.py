import math

# Начальное значение произведения (обязательно 1, а не 0!)
product = 1

# Цикл от 1 до 20 включительно
for n in range(1, 21):
    # Считаем числитель: ln(3^n + n^2 + 1)
    # 3**n - это 3 в степени n
    numerator = math.log(3**n + n**2 + 1)
    
    # Считаем знаменатель: lg(n^5 + 2^(3n) + 1)
    # 2**(3*n) - это 2 в степени 3n
    denominator = math.log10(n**5 + 2**(3*n) + 1)
    
    # Считаем текущий множитель
    term = numerator / denominator
    
    # Умножаем общее произведение на текущий множитель
    product *= term

# Выводим результат
print(f"Произведение P = {product}")